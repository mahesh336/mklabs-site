-- 1. Developer profiles
create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    role text not null default 'developer'
        check (role in ('developer', 'admin')),
    created_at timestamptz not null default now()
);

-- 2. Attendance records
create table public.attendance (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    clock_in timestamptz not null default now(),
    clock_out timestamptz,
    created_at timestamptz not null default now(),

    check (clock_out is null or clock_out >= clock_in)
);

-- Only one active clock-in per developer
create unique index one_active_attendance_per_user
on public.attendance (user_id)
where clock_out is null;


-- ============================================
-- 3. AUTOMATIC PROFILE CREATION
-- ============================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

    insert into public.profiles (id, full_name)
    values (
        new.id,
        coalesce(
            new.raw_user_meta_data ->> 'full_name',
            new.email
        )
    );

    return new;

end;
$$;


create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();


-- ============================================
-- 4. ADMIN CHECK FUNCTION
-- ============================================

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
        and role = 'admin'
    );
$$;


-- ============================================
-- 5. CLOCK IN
-- ============================================

create or replace function public.clock_in()
returns public.attendance
language plpgsql
security definer
set search_path = public
as $$
declare
    result public.attendance;
begin

    if auth.uid() is null then
        raise exception 'You must be logged in';
    end if;

    insert into public.attendance (user_id)
    values (auth.uid())
    returning * into result;

    return result;

exception
    when unique_violation then
        raise exception 'You are already clocked in';
end;
$$;


-- ============================================
-- 6. CLOCK OUT
-- ============================================

create or replace function public.clock_out()
returns public.attendance
language plpgsql
security definer
set search_path = public
as $$
declare
    result public.attendance;
begin

    if auth.uid() is null then
        raise exception 'You must be logged in';
    end if;

    update public.attendance
    set clock_out = now()
    where user_id = auth.uid()
      and clock_out is null
    returning * into result;

    if result.id is null then
        raise exception 'You are not currently clocked in';
    end if;

    return result;

end;
$$;


-- ============================================
-- 7. ENABLE ROW LEVEL SECURITY
