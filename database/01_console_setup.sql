alter table public.profiles enable row level security;
alter table public.attendance enable row level security;


-- ============================================
-- 8. PROFILE SECURITY
-- ============================================

-- Developers can see their own profile
create policy "Users can view own profile"
on public.profiles
for select
to authenticated
using (
    id = auth.uid()
);

-- Admins can see all profiles
create policy "Admins can view all profiles"
on public.profiles
for select
to authenticated
using (
    public.is_admin()
);


-- ============================================
-- 9. ATTENDANCE SECURITY
-- ============================================

-- Developers can see their own attendance
create policy "Users can view own attendance"
on public.attendance
for select
to authenticated
using (
    user_id = auth.uid()
);

-- Admins can see all attendance
create policy "Admins can view all attendance"
on public.attendance
for select
to authenticated
using (
    public.is_admin()
);


-- ============================================
-- 10. WORKING HOURS VIEW
-- ============================================

create or replace view public.attendance_summary
with (security_invoker = true)
as
select
    a.id,
    a.user_id,
    p.full_name,
    p.role,
    a.clock_in,
    a.clock_out,

    case
        when a.clock_out is not null
        then extract(epoch from (a.clock_out - a.clock_in))
        else extract(epoch from (now() - a.clock_in))
    end as working_seconds

from public.attendance a
join public.profiles p
    on p.id = a.user_id;


